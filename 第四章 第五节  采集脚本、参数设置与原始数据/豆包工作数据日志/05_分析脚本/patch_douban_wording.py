"""把豆瓣消遣词“均为0”的表述精确化为子串计数口径（毒舌/吐槽各1次且为批评语境）。"""
import os
import docx
BASE = r'F:\文学数字人文阐释实践\故事新编研究案例\第五节《故事新编》数字传播生态的算法规训批判'
DST = os.path.join(BASE,'第五节_数字副文本采集与修订交付_20260912','03_论文修订稿',
    '第五节 接受-批判进路：《故事新编》数字传播生态的算法规训批判（数字副文本实证修订稿）.docx')
d = docx.Document(DST)

PAIRS = [
 ("并未出现初始方案预期的“毒舌”“吐槽”“爽文”“互联网嘴替”“魔改”“玩梗”等消遣性标签，逐词核验其词频均为0；样本中与解构取向相关的词汇是“解构”（11）、“戏谑”（9）、“荒诞”（9）、“讽刺”（8），它们属于文学批评话语",
  "初始方案预期的消遣性标签并未形成话语集群：以全文子串逐词核验，“爽文”“嘴替”“互联网嘴替”“魔改”“整活”“玩梗”出现次数均为0，“毒舌”“吐槽”各仅1次，且二者都用于传统文学批评语境（一处以“毒舌之王”形容鲁迅文笔犀利，一处以“《理水》吐槽顾颉刚”分析小说的真人影射），没有一条把作品归类为“毒舌爽文”；样本中真正成规模的解构取向词汇是“解构”（11）、“戏谑”（9）、“荒诞”（9）、“讽刺”（8）（jieba分词词频口径），它们属于文学批评话语"),
 ("实测200条短评中这些词词频均为0，高频词反而是篇目名《铸剑》",
  "实测200条短评中“爽文”“嘴替”等词为0、“毒舌”“吐槽”各仅1次且用于批评语境，高频词反而是篇目名《铸剑》"),
]
hit = [0,0]
for p in d.paragraphs:
    for r in p.runs:
        for i,(old,new) in enumerate(PAIRS):
            if old in r.text:
                r.text = r.text.replace(old,new); hit[i]+=1
print('替换命中:', hit)
assert hit==[1,1], '存在未命中替换，需检查'
d.save(DST)
print('已保存')
