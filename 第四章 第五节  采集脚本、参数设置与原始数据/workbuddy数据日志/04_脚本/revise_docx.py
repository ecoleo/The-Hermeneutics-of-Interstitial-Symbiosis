def replace_in_paragraph(p, old, new):
    full = "".join(r.text for r in p.runs)
    if old not in full:
        return False
    newfull = full.replace(old, new)
    if not p.runs:
        return False
    p.runs[0].text = newfull
    for r in p.runs[1:]:
        r.text = ""
    return True


def insert_paragraph_after(paragraph):
    new_p = OxmlElement("w:p")
    paragraph._p.addnext(new_p)
    return Paragraph(new_p, paragraph._parent)


def insert_figure(anchor, img_path, caption):
    pic_p = insert_paragraph_after(anchor)
    pic_p.alignment = WD_ALIGN_PARAGRAPH.CENTER
    pic_p.add_run().add_picture(img_path, width=Cm(13.5))
    cap_p = insert_paragraph_after(pic_p)
    cap_p.alignment = WD_ALIGN_PARAGRAPH.CENTER
    run = cap_p.add_run(caption)
    run.font.size = Pt(9)
    run.font.name = "宋体"
    run._element.rPr.rFonts.set(qn("w:eastAsia"), "宋体")
    return cap_p


def main():
    os.makedirs(DST_DIR, exist_ok=True)
    shutil.copy2(SRC, DST)
    doc = docx.Document(DST)

    misses = []
    hits = 0
    for i, (old, new) in enumerate(R, 1):
        found = 0
        for p in doc.paragraphs:
            full = "".join(r.text for r in p.runs)
            if old in full:
                found += 1
                replace_in_paragraph(p, old, new)
        if found != 1:
            misses.append((i, found, old[:40]))
        else:
            hits += 1
    if misses:
        print("替换未唯一命中，中止：")
        for i, c, s in misses:
            print(f"  R{i}: 命中{c}次 | {s}…")
        sys.exit(1)
    print(f"文本替换 {hits}/{len(R)} 处全部唯一命中")

    fig_count = 0
    for anchor_tail, figs in FIGS:
        anchor = None
        for p in doc.paragraphs:
            full = "".join(r.text for r in p.runs)
            if anchor_tail in full:
                anchor = p
        if anchor is None:
            print(f"图锚点未找到: {anchor_tail[:30]}…"); sys.exit(1)
        cur = anchor
        for img, cap in figs:
            cur = insert_figure(cur, os.path.join(FIG, img), cap)
            fig_count += 1
    doc.save(DST)
    print(f"插图 {fig_count} 张，已保存: {DST}")

    # 回读校验
    import zipfile, re
    xml = zipfile.ZipFile(DST).read("word/document.xml").decode("utf-8")
    text = "".join(re.findall(r"<w:t[^>]*>(.*?)</w:t>", xml, re.S))
    bad_new = [new[:30] for old, new in R if new not in text]
    bad_old = [old[:30] for old, new in R if old in text]
    n_img = xml.count("<pic:pic")
    print(f"校验: 新表述缺失={len(bad_new)} 旧表述残留={len(bad_old)} 图片数={n_img}")
    for s in bad_new:
        print("  缺:", s)
    for s in bad_old:
        print("  残:", s)


if __name__ == "__main__":
    main()
