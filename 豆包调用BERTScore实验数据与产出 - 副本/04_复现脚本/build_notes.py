def setfont(run, size=12, east='宋体', bold=False):
    run.font.name = 'Times New Roman'; run.font.size = Pt(size); run.bold = bold
    rPr = run._element.get_or_add_rPr()
    rf = rPr.find(qn('w:rFonts'))
    if rf is None:
        rf = OxmlElement('w:rFonts'); rPr.append(rf)
    rf.set(qn('w:eastAsia'), east)

def title(text, size=15):
    p = doc.add_paragraph(); p.alignment = WD_ALIGN_PARAGRAPH.CENTER
    setfont(p.add_run(text), size, '黑体', True)
    return p

def h(text, size=12.5):
    p = doc.add_paragraph(); setfont(p.add_run(text), size, '黑体', True)
    p.paragraph_format.space_before = Pt(8); p.paragraph_format.space_after = Pt(4)
    return p

def body(text, indent=True):
    p = doc.add_paragraph()
    pf = p.paragraph_format
    pf.line_spacing = Pt(22)
    if indent: pf.first_line_indent = Pt(24)
    setfont(p.add_run(text), 12, '宋体')
    return p

def item(label, text):
    p = doc.add_paragraph()
    pf = p.paragraph_format; pf.line_spacing = Pt(22); pf.first_line_indent = Pt(24)
    setfont(p.add_run(label), 12, '黑体', True)
    setfont(p.add_run(text), 12, '宋体')
    return p

